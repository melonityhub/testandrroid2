#!/usr/bin/env python3
"""Regenerates FdData.java (POS / category tables + Persian normalisation
tables) from the dictionaryproject repo.

  python3 scripts/gen-fddata.py /path/to/dictionaryproject/fastdic_desktop/fd_data.py
"""
import importlib.util
import os
import sys

src_path = sys.argv[1] if len(sys.argv) > 1 else '../../dictionaryproject/fastdic_desktop/fd_data.py'
spec = importlib.util.spec_from_file_location('fd', src_path)
fd = importlib.util.module_from_spec(spec)
spec.loader.exec_module(fd)


def jstr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif 32 <= o < 127:
            out.append(ch)
        else:
            out.append('\\u%04x' % o)
    return '"' + ''.join(out) + '"'


def jmap(name, d):
    keys = sorted(d)
    lines = [f'    static final String[] {name} = new String[{max(keys) + 1}];', '    static {']
    for k in keys:
        lines.append(f'        {name}[{k}] = {jstr(d[k])};')
    lines.append('    }')
    return '\n'.join(lines)


src = '''package app.proudvocab.android;

/** GENERATED by scripts/gen-fddata.py from dictionaryproject/fd_data.py - do not edit by hand. */
final class FdData {
    private FdData() { }

'''
src += jmap('POS_EN', fd.POS_EN) + '\n\n' + jmap('POS_EN_FA', fd.POS_EN_TO_FA) + '\n\n'
src += jmap('POS_FA', fd.POS_FA) + '\n\n' + jmap('POS_FA_EN', fd.POS_FA_TO_EN) + '\n\n'
src += jmap('CATEGORY', fd.CATEGORY_NAMES) + '\n\n'
src += '    static final int[] BROKEN = {' + ', '.join(str(x) for x in fd.BROKEN_CHARS) + '};\n'
src += '    static final int[] CORRECT = {' + ', '.join(str(x) for x in fd.CORRECT_CHARS) + '};\n\n'
src += '    /** sequential replacements used to build the word_in_number column */\n    static final String[][] PE_TO_NUMBER = {\n'
for a, b in fd.PE_TO_NUMBER:
    src += f'        {{{jstr(a)}, {jstr(b)}}},\n'
src += '    };\n\n'
src += '''    static String pos(String[] table, int id) {
        return id >= 0 && id < table.length && table[id] != null ? table[id] : "";
    }
}
'''
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'app/src/main/java/app/proudvocab/android/FdData.java')
open(out, 'w', encoding='utf8').write(src)
print('wrote', os.path.normpath(out))
